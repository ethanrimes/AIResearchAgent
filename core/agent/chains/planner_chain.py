"""
Planner Chain module for the AI Research Agent.

This module is responsible for planning experiments to test the hypotheses
generated by the HypothesisChain. It creates a high-level plan without any code.
"""

import os
import json
import logging
from pathlib import Path
from typing import Dict, List, Any

from langchain.chains import LLMChain
from langchain.prompts import PromptTemplate
from langchain.tools import BaseTool
from langchain.agents import AgentExecutor, create_structured_chat_agent

# Import custom tools
from core.agent.tools.read_file import ReadFileTool
# WRITE-file tool removed

from core.agent.tools.read_scratchpad import ReadScratchpadTool
from core.agent.tools.write_to_scratchpad import WriteScratchpadTool

from core.agent.schemas.output_schemas import PlannerOutput
from core.utils.path_utils import get_active_run_path

class PlannerChain:
    """
    Chain responsible for planning experiments to test hypotheses.
    """
    
    def __init__(self, llm, workspace: Dict[str, Path], directive: str):
        """
        Initialize the PlannerChain.
        
        Args:
            llm: The language model to use.
            workspace: Dictionary containing paths to workspace directories.
            directive: The system directive for the agent.
        """
        self.llm = llm
        self.workspace = workspace
        self.directive = directive
        self.output_file = workspace["planning"] / "experiment_plan.json"
        self.scratchpad_file = workspace["scratchpad"] / "planner_notes.txt"

        self.logger = logging.getLogger("ai_research_agent.planner_chain")
        
        # Initialize tools
        self.tools = self._init_tools()
        
        # Initialize agent
        self.agent = self._init_agent()
        
        self.logger.info("PlannerChain initialized")
        
    def _init_tools(self) -> List[BaseTool]:
        """
        Initialize the tools for the planner agent.
        
        Returns:
            List of tools.
        """
        # For planner chain, we can read from read_only and hypothesis
        read_tool = ReadFileTool(
            allowed_dirs=[
                str(self.workspace["read_only"]),
                str(self.workspace["hypothesis"])
            ]
        )
        
        read_scratchpad_tool = ReadScratchpadTool(
            scratchpad_file=str(self.scratchpad_file)
        )
        
        write_scratchpad_tool = WriteScratchpadTool(
            scratchpad_file=str(self.scratchpad_file)
        )
        
        return [
            read_tool,
            read_scratchpad_tool,
            write_scratchpad_tool
        ]
        
    def _init_agent(self) -> AgentExecutor:
        """
        Initialize the planner agent.
        """
        prompt = PromptTemplate.from_template(
            template=(
                f"{self.directive}\n\n"
                "Tool names you can call: {tool_names}\n\n"
                "Full tool descriptions:\n{tools}\n\n"
                "{input}\n\n"
                "{agent_scratchpad}"
            )
        )

        agent = create_structured_chat_agent(
            llm=self.llm,
            tools=self.tools,
            prompt=prompt,
            stop_sequence=False
        )

        return AgentExecutor(
            agent=agent,
            tools=self.tools,
            verbose=True,
            max_iterations=10
        )
        
    def run(self, hypothesis_data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Run the experiment planning process.
        
        Args:
            hypothesis_data: The hypotheses generated by the HypothesisChain.
            
        Returns:
            Dict containing the experiment plan.
        """
        self.logger.info("Running experiment planning")
        
        # ------------------------------------------------------------------
        # Build output path dynamically from the active run directory
        # ------------------------------------------------------------------
        run_dir = get_active_run_path()
        output_path = run_dir / "planning" / "experiment_plan.json"
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Find the hypothesis file path to read from
        hypothesis_file = self.workspace["hypothesis"] / "hypotheses.json"
        
        # ------------------------------------------------------------------
        # Structured invocation
        # ------------------------------------------------------------------
        runnable = self.agent.with_structured_output(PlannerOutput)
        result: PlannerOutput = runnable.invoke(
            {"input": f"Read the hypotheses from: {hypothesis_file}\n"
                      f"Generate an experiment plan based on these hypotheses and "
                      f"return it following the required JSON schema."}
        )
        
        # Persist
        output_path.write_text(result.model_dump_json(indent=2), encoding="utf-8")
        self.logger.info(f"Wrote experiment plan to {output_path}")
        
        return result.model_dump()