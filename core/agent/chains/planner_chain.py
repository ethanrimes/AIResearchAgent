"""
Planner Chain module for the AI Research Agent.

This module is responsible for planning experiments to test the hypotheses
generated by the HypothesisChain. It creates a high-level plan without any code.
"""

import json
import logging
import time  # Added import for timing
from pathlib import Path
from typing import Dict, Any

from langchain.chains import LLMChain
from langchain.prompts import PromptTemplate

from core.agent.schemas.output_schemas import PlannerOutput
from core.utils.path_utils import get_active_run_path
from core.utils.logging_utils import log_agent_invoke  # Added import for logging

class PlannerChain:
    """
    Chain responsible for planning experiments to test hypotheses.
    """
    
    def __init__(self, llm, workspace: Dict[str, Path], directive: str):
        """
        Initialize the PlannerChain.
        
        Args:
            llm: The language model to use.
            workspace: Dictionary containing paths to workspace directories.
            directive: The system directive for the agent.
        """
        self.llm = llm
        self.workspace = workspace
        self.directive = directive
        self.output_file = workspace["planning"] / "experiment_plan.json"
        
        self.logger = logging.getLogger("ai_research_agent.planner_chain")
        
        # Initialize the chain
        self.chain = self._init_chain()
        
        self.logger.info("PlannerChain initialized")
        
    def _init_chain(self) -> LLMChain:
        """
        Initialize the LLM chain with the appropriate prompt.
        
        Returns:
            Initialized LLMChain
        """
        prompt = PromptTemplate.from_template(
            template=(
                f"{self.directive}\n\n"
                "# Example Experiment Plan\n"
                "For reference, here is an example of what a well-structured experiment plan looks like:\n"
                "```\n"
                "sandbox/read_only/example/experiment_plan.json\n"
                "```\n\n"
                "# Generated Hypotheses\n"
                "{hypotheses_content}\n\n"
                "{input}\n\n"
            )
        )

        return LLMChain(
            llm=self.llm,
            prompt=prompt
        )
        
    def run(self, hypothesis_data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Run the experiment planning process.
        
        Args:
            hypothesis_data: The hypotheses generated by the HypothesisChain.
            
        Returns:
            Dict containing the experiment plan.
        """
        self.logger.info("Running experiment planning")
        
        # Start timing the execution
        start_time = time.time()
        
        # ------------------------------------------------------------------
        # Use direct path to planning directory at root level
        # ------------------------------------------------------------------
        output_path = Path("/planning/experiment_plan.json")
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Find the hypothesis file path to read from
        hypothesis_file = Path("/hypothesis/hypotheses.json")
        
        # Read the hypotheses data directly
        hypotheses_content = json.dumps(hypothesis_data, indent=2)
        
        # ------------------------------------------------------------------
        # Structured invocation with the chain
        # ------------------------------------------------------------------
        # Prepare input with hypotheses data embedded
        input_text = "Generate an experiment plan based on these hypotheses. " \
                     "The plan should include a baseline, test plans for each hypothesis, " \
                     "evaluation metrics, and an analysis approach. " \
                     "Return the plan following the required JSON schema for PlannerOutput."
        
        # Run the chain with structured output
        result = self.llm.with_structured_output(PlannerOutput).invoke(
            self.chain.prompt.format(
                hypotheses_content=hypotheses_content,
                input=input_text
            )
        )
        
        # Persist
        output_path.write_text(result.model_dump_json(indent=2), encoding="utf-8")
        self.logger.info(f"Wrote experiment plan to {output_path}")
        
        # Calculate execution time
        execution_time = time.time() - start_time
        
        # Log agent invocation details
        log_agent_invoke(
            agent_name="PlannerChain",
            runtime=execution_time,
            intermediate_steps=[]  # PlannerChain doesn't have intermediate steps to log
        )
        
        return result.model_dump()